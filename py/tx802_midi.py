"""Strict, dependency-free format-1 SMF encoding for projected MIDI records.

Records carry complete channel messages, canonical meta events, or complete raw
F0...F7 SysEx messages. No musical projection or voice generation occurs here.
"""
from dataclasses import dataclass
import struct

_MAX_VLQ = 0x0FFFFFFF


@dataclass(frozen=True)
class MidiRecord:
    tick: int
    track: int
    order: int
    data: bytes


def _integer(value, name, low, high):
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{name} must be an integer")
    if not low <= value <= high:
        raise ValueError(f"{name} must be in {low}..{high}")
    return value


def _vlq(value):
    _integer(value, "VLQ", 0, _MAX_VLQ)
    result = [value & 127]
    while value > 127:
        value >>= 7
        result.insert(0, (value & 127) | 128)
    return bytes(result)


def _read_vlq(data, offset):
    value = 0
    for _ in range(4):
        if offset >= len(data):
            raise ValueError("truncated VLQ")
        byte = data[offset]
        offset += 1
        value = (value << 7) | (byte & 127)
        if not byte & 128:
            return value, offset
    raise ValueError("VLQ exceeds four bytes")


def meta(kind, data):
    """Build a canonical meta event; callers encode text as UTF-8 bytes."""
    _integer(kind, "meta kind", 0, 127)
    if not isinstance(data, bytes):
        raise TypeError("meta data must be bytes")
    return bytes((255, kind)) + _vlq(len(data)) + data


def _validate_message(data, *, allow_eot=False):
    if not isinstance(data, bytes):
        raise TypeError("MIDI event data must be bytes")
    if not data:
        raise ValueError("empty MIDI event")
    status = data[0]
    if 0x80 <= status <= 0xEF:
        size = 2 if status & 0xF0 in (0xC0, 0xD0) else 3
        if len(data) != size or any(byte > 127 for byte in data[1:]):
            raise ValueError("invalid channel message width or data byte")
    elif status == 0xF0:
        if len(data) < 2 or data[-1] != 0xF7 or any(byte > 127 for byte in data[1:-1]):
            raise ValueError("SysEx must be a complete F0...F7 message with 7-bit payload")
        _vlq(len(data) - 1)
    elif status == 0xFF:
        if len(data) < 3 or data[1] > 127:
            raise ValueError("invalid meta event")
        length, start = _read_vlq(data, 2)
        if start + length != len(data):
            raise ValueError("meta event length mismatch")
        kind = data[1]
        if kind == 0x2F and (not allow_eot or length != 0):
            raise ValueError("End of Track is generated by the encoder")
        fixed_lengths = {0x20: 1, 0x21: 1, 0x51: 3, 0x54: 5, 0x58: 4, 0x59: 2}
        if kind in fixed_lengths and length != fixed_lengths[kind]:
            raise ValueError("invalid fixed-length meta event")
        if kind in (0x20, 0x21) and data[start] > (15 if kind == 0x20 else 127):
            raise ValueError("invalid MIDI channel/port meta value")
    else:
        raise ValueError("unsupported MIDI status (full channel status, F0 SysEx or meta required)")


def encode_smf(records, *, ppq=480, end_tick, tempo_us=500000,
               track_names=None, track_ports=None):
    """Encode records deterministically, retaining the shared silence interval.

    Track zero receives tempo at tick zero. Missing tracks receive a valid EOT.
    Equal tick/order records retain their input order. All tracks end at end_tick.
    """
    _integer(ppq, "ppq", 1, 32767)
    _integer(end_tick, "end_tick", 0, _MAX_VLQ)
    _integer(tempo_us, "tempo_us", 1, 0xFFFFFF)
    names = {} if track_names is None else track_names
    ports = {} if track_ports is None else track_ports
    if not isinstance(names, dict) or not isinstance(ports, dict):
        raise TypeError("track_names and track_ports must be dictionaries")
    tracks = {0: []}
    for track, name in names.items():
        _integer(track, "track", 0, 65534)
        if not isinstance(name, str):
            raise TypeError("track name must be a string")
        tracks.setdefault(track, [])
    for track, port in ports.items():
        _integer(track, "track", 0, 65534)
        _integer(port, "port", 0, 127)
        tracks.setdefault(track, [])
    for record in records:
        if not isinstance(record, MidiRecord):
            raise TypeError("records must contain MidiRecord objects")
        _integer(record.tick, "tick", 0, _MAX_VLQ)
        _integer(record.track, "track", 0, 65534)
        _integer(record.order, "order", 0, _MAX_VLQ)
        if record.tick > end_tick:
            raise ValueError("event occurs after end_tick")
        _validate_message(record.data)
        tracks.setdefault(record.track, []).append(record)
    count = max(tracks) + 1
    output = bytearray(b"MThd" + struct.pack(">IHHH", 6, 1, count, ppq))
    for track in range(count):
        body = bytearray()
        if track == 0:
            body += b"\x00" + meta(0x51, tempo_us.to_bytes(3, "big"))
        if track in names:
            body += b"\x00" + meta(3, names[track].encode("utf-8"))
        if track in ports:
            body += b"\x00" + meta(0x21, bytes((ports[track],)))
        previous = 0
        for record in sorted(tracks.get(track, []), key=lambda item: (item.tick, item.order)):
            body += _vlq(record.tick - previous)
            if record.data[0] == 0xF0:
                body += b"\xF0" + _vlq(len(record.data) - 1) + record.data[1:]
            else:
                body += record.data
            previous = record.tick
        body += _vlq(end_tick - previous) + meta(0x2F, b"")
        if len(body) > 0xFFFFFFFF:
            raise ValueError("track chunk exceeds SMF length limit")
        output += b"MTrk" + struct.pack(">I", len(body)) + body
    return bytes(output)


def decode_smf(data):
    """Inspect format-1 PPQ SMF as absolute ticks and canonical event bytes.

    EOT and other meta events are retained. Channel running status is accepted;
    incomplete SysEx packets and F7 escape packets are deliberately rejected.
    """
    if not isinstance(data, bytes):
        raise TypeError("SMF data must be bytes")
    if len(data) < 14 or data[:4] != b"MThd":
        raise ValueError("missing or truncated SMF header")
    length, fmt, count, ppq = struct.unpack(">IHHH", data[4:14])
    if length != 6 or fmt != 1 or count == 0 or not 1 <= ppq <= 32767:
        raise ValueError("expected format-1 SMF with PPQ timing")
    offset = 14
    tracks = []
    for _ in range(count):
        if offset + 8 > len(data) or data[offset:offset + 4] != b"MTrk":
            raise ValueError("missing or truncated track chunk")
        size = int.from_bytes(data[offset + 4:offset + 8], "big")
        offset += 8
        if offset + size > len(data):
            raise ValueError("track chunk exceeds file bounds")
        body = data[offset:offset + size]
        offset += size
        position = tick = 0
        running = None
        events = []
        ended = False
        while position < len(body):
            delta, position = _read_vlq(body, position)
            tick += delta
            if tick > _MAX_VLQ or position >= len(body):
                raise ValueError("invalid event tick or truncated status")
            start = position
            status = body[position]
            if status < 128:
                if running is None:
                    raise ValueError("running status without channel status")
                status = running
            else:
                position += 1
            if 0x80 <= status <= 0xEF:
                width = 1 if status & 0xF0 in (0xC0, 0xD0) else 2
                if position + width > len(body):
                    raise ValueError("truncated channel event")
                event = bytes((status,)) + body[position:position + width]
                position += width
                running = status
            elif status == 0xFF:
                running = None
                if position >= len(body):
                    raise ValueError("truncated meta kind")
                kind = body[position]
                position += 1
                size, position = _read_vlq(body, position)
                if position + size > len(body):
                    raise ValueError("truncated meta event")
                event = meta(kind, body[position:position + size])
                position += size
                ended = kind == 0x2F
            elif status == 0xF0:
                running = None
                size, position = _read_vlq(body, position)
                if position + size > len(body):
                    raise ValueError("truncated SysEx event")
                event = b"\xF0" + body[position:position + size]
                position += size
            else:
                raise ValueError("unsupported SMF status")
            _validate_message(event, allow_eot=True)
            events.append((tick, event))
            if ended:
                if position != len(body):
                    raise ValueError("data after End of Track")
                break
            if position <= start:
                raise ValueError("event parser did not advance")
        if not ended:
            raise ValueError("track is missing End of Track")
        tracks.append(events)
    if offset != len(data):
        raise ValueError("trailing data after SMF tracks")
    return {"ppq": ppq, "tracks": tracks}
